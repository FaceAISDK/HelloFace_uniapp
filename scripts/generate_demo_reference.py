#!/usr/bin/env python3
"""Generate simple UTS constants from the checked-in fictional SDK reference."""
import base64
import hashlib
import json
from pathlib import Path
import re
import struct


def generate(root):
    image = (root / 'static/demo-face.png').read_bytes()
    data = json.loads((root / 'demo/face-reference.json').read_text())
    sdk = json.loads((root / 'sdk-artifacts.json').read_text())
    if image[:8] != b'\x89PNG\r\n\x1a\n' or struct.unpack('>II', image[16:24]) != (200, 200):
        raise ValueError('Demo image must be a 200x200 PNG')
    if hashlib.sha256(image).hexdigest() != data['imageSha256']:
        raise ValueError('Demo image changed; re-extract its feature with the real SDK first')
    if data['featureSpaceID'] != 'jdx-feature-v1' or not re.fullmatch(r'HF1:[A-Za-z0-9_-]{600}', data['feature']):
        raise ValueError('Invalid SDK demo reference')
    if data['sdkVersion'] != sdk['version']:
        raise ValueError('SDK changed; re-extract and verify the fictional demo reference before preparing examples')
    constants = {'demoImageBase64': base64.b64encode(image).decode('ascii'),
                 'demoFeature': data['feature'], 'demoFeatureSpaceID': data['featureSpaceID']}
    source = '// Generated by scripts/generate_demo_reference.py. Fictional demo data only.\n'
    source += ''.join(f'export const {key} = {json.dumps(value)}\n' for key, value in constants.items())
    # JS supports both Vue2/Vue3; uvue imports UTS. Both carry identical constants.
    for extension in ('js', 'uts'):
        (root / f'demo/face-reference.{extension}').write_text(source)


if __name__ == '__main__':
    generate(Path(__file__).resolve().parents[1])
