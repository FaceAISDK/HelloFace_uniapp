#!/usr/bin/env python3
"""Generate the native presentation constants from one shared, SDK-independent spec."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / 'uni_modules/HelloFace-Verify'
SPEC = PLUGIN / 'native-ui.json'


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def render(spec, language):
    header = '// Generated by scripts/generate_native_ui.py from native-ui.json. Do not edit.\n'
    if language == 'kt':
        lines = [header, 'package uts.sdk.modules.HelloFaceVerify\n', 'internal object HelloFaceVerifyPresentation {']
    elif language == 'swift':
        lines = [header, 'import UIKit\n', 'enum HelloFaceVerifyPresentation {']
    else:
        lines = [header, 'export class HelloFaceVerifyPresentation {']
    for group in ('colors', 'text', 'metrics', 'fonts', 'values'):
        prefix = {'colors': 'color', 'text': '', 'metrics': '', 'fonts': 'font', 'values': ''}[group]
        for key, value in spec[group].items():
            name = prefix + key[0].upper() + key[1:] if prefix else key
            if group == 'colors':
                rgb = int(value[1:], 16)
                if language == 'kt':
                    definition = f'const val {name}: Int = {rgb - 0x1000000}'
                elif language == 'swift':
                    components = ', '.join(f'{c}: {n}.0/255' for c, n in zip(('red', 'green', 'blue'),
                        ((rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255)))
                    definition = f'static let {name} = UIColor({components}, alpha: 1)'
                else:
                    definition = f'static readonly {name}: string = {quoted(value)};'
            elif group == 'text':
                definition = {'kt': f'const val {name}: String = {quoted(value)}',
                    'swift': f'static let {name} = {quoted(value)}',
                    'ets': f'static readonly {name}: string = {quoted(value)};'}[language]
            else:
                floating = group == 'values' or (group == 'fonts' and language == 'kt')
                literal = str(float(value)) + ('f' if language == 'kt' else '') if floating else str(value)
                definition = {'kt': f'const val {name}: {"Float" if floating else "Int"} = {literal}',
                    'swift': f'static let {name}: CGFloat = {literal}',
                    'ets': f'static readonly {name}: number = {literal};'}[language]
            lines.append('    ' + definition)
    if language == 'kt':
        lines += ['\n    fun guidance(stage: String, action: String?): String {',
            '        if (stage == "PERFORM_ACTION") return when (action) {']
        lines += [f'            {quoted(k)} -> {quoted(v)}' for k, v in spec['actions'].items()]
        lines += ['            else -> actionFallback', '        }', '        return when (stage) {']
        lines += [f'            {quoted(k)} -> {quoted(v)}' for k, v in spec['stages'].items()]
        lines += ['            else -> stageFallback', '        }', '    }',
            '    fun phase(enrollment: Boolean, stage: String = "", step: Int = 0, count: Int = 0): String =',
            '        if (stage == "PERFORM_ACTION" && count > 0) "$actionPhase · $step/$count"',
            '        else if (enrollment) enrollPhase else verifyPhase',
            '    fun isWarning(stage: String): Boolean = stage in listOf(' + ', '.join(map(quoted, spec['warningStages'])) + ')']
    elif language == 'swift':
        lines += ['\n    static func guidance(stage: String, action: String?) -> String {',
            '        if stage == "PERFORM_ACTION" {', '            switch action {']
        lines += [f'            case {quoted(k)}: return {quoted(v)}' for k, v in spec['actions'].items()]
        lines += ['            default: return actionFallback', '            }', '        }', '        switch stage {']
        lines += [f'        case {quoted(k)}: return {quoted(v)}' for k, v in spec['stages'].items()]
        lines += ['        default: return stageFallback', '        }', '    }',
            '    static func phase(enrollment: Bool, stage: String = "", step: Int = 0, count: Int = 0) -> String {',
            r'        if stage == "PERFORM_ACTION" && count > 0 { return "\(actionPhase) · \(step)/\(count)" }',
            '        return enrollment ? enrollPhase : verifyPhase', '    }',
            '    static func isWarning(stage: String) -> Bool {',
            '        return [' + ', '.join(map(quoted, spec['warningStages'])) + '].contains(stage)', '    }']
    else:
        lines += ['\n    static guidance(stage: string, action: string | undefined): string {',
            "        if (stage === 'PERFORM_ACTION') {", '            switch (action) {']
        lines += [f'                case {quoted(k)}: return {quoted(v)};' for k, v in spec['actions'].items()]
        lines += ['                default: return HelloFaceVerifyPresentation.actionFallback;', '            }',
            '        }', '        switch (stage) {']
        lines += [f'            case {quoted(k)}: return {quoted(v)};' for k, v in spec['stages'].items()]
        lines += ['            default: return HelloFaceVerifyPresentation.stageFallback;', '        }', '    }',
            '    static phase(enrollment: boolean, stage: string = "", step: number = 0, count: number = 0): string {',
            '        if (stage === "PERFORM_ACTION" && count > 0) return `${HelloFaceVerifyPresentation.actionPhase} · ${step}/${count}`;',
            '        return enrollment ? HelloFaceVerifyPresentation.enrollPhase : HelloFaceVerifyPresentation.verifyPhase;', '    }',
            '    static isWarning(stage: string): boolean {',
            '        return [' + ', '.join(map(quoted, spec['warningStages'])) + '].includes(stage);', '    }']
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in native files are stale')
    args = parser.parse_args()
    spec = json.loads(SPEC.read_text())
    stale = []
    for platform, extension in [('android', 'kt'), ('ios', 'swift'), ('harmony', 'ets')]:
        target = PLUGIN / f'utssdk/app-{platform}/HelloFaceVerifyPresentation.{extension}'
        expected = render(spec, extension)
        if args.check:
            if not target.is_file() or target.read_text() != expected:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(expected)
    if stale:
        parser.exit(1, 'Native UI is stale. Run npm run ui:build:\n' + '\n'.join(stale) + '\n')
    print('Native UI: Android, iOS and HarmonyOS ' + ('match the shared spec' if args.check else 'generated'))


if __name__ == '__main__':
    main()
