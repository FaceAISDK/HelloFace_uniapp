#!/usr/bin/env python3
"""Shared Android debug protocol, source stamp, device selection and scoped logs."""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time
import uuid
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = Path('uni_modules/HelloFace-Verify/utssdk')
STAMP = 'HelloFaceVerifyBuildInfo.kt'
RECEIVER = 'uts.sdk.modules.HelloFaceVerify.HelloFaceVerifyDebugReceiver'
ACTION = 'uts.sdk.modules.HelloFaceVerify.DEBUG_'
MAX_BYTES = 32 * 1024 * 1024


def run(args, timeout=30, **kwargs):
    result = subprocess.run([str(v) for v in args], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            timeout=timeout, **kwargs)
    if result.returncode:
        error = (result.stderr or result.stdout or b'').decode(errors='replace').strip()
        raise RuntimeError(error or f'Command failed: {args[0]}')
    return result.stdout.decode(errors='replace').strip()


def fingerprint(root=ROOT):
    root = Path(root)
    uts = root / PLUGIN
    paths = [p for p in (uts / 'app-android').rglob('*') if p.is_file() and p.name != STAMP
             and not any(part.startswith('.') for part in p.relative_to(uts).parts)
             and not p.name.endswith(('.tmp', '.swp', '~'))]
    paths += [uts / name for name in ['interface.uts', 'shared.uts', 'unierror.uts']]
    digest = hashlib.sha256()
    for path in sorted(paths, key=lambda p: p.relative_to(uts).as_posix()):
        digest.update(path.relative_to(uts).as_posix().encode() + b'\0')
        digest.update(hashlib.sha256(path.read_bytes()).digest())
    return 'hfv1:' + digest.hexdigest()


def prepare(root=ROOT):
    root = Path(root)
    value = fingerprint(root)
    path = root / PLUGIN / 'app-android' / STAMP
    content = ('// Generated by npm run android:prepare. Rebuild the base after native changes.\n'
               'package uts.sdk.modules.HelloFaceVerify\n\n'
               'internal object HelloFaceVerifyBuildInfo {\n'
               f'    const val FINGERPRINT = "{value}"\n' + '}\n')
    if not path.exists() or path.read_text() != content:
        path.write_text(content)
    return value


def host_fingerprint(project):
    manifest = json.loads((Path(project) / 'manifest.json').read_text())
    android = manifest.get('app-plus', {}).get('distribute', {}).get('android') or manifest.get('app-android', {}).get('distribute', {})
    def public(value):
        if isinstance(value, dict):
            return {key: public(item) for key, item in value.items()
                    if not any(word in key.lower() for word in ['password', 'cert', 'keystore', 'signing'])}
        if isinstance(value, list):
            return [public(item) for item in value]
        return value
    source = {key: manifest.get(key) for key in ['appid', 'versionName', 'versionCode']}
    source.update(android=public(android), uvue=(Path(project) / 'App.uvue').exists())
    icons = manifest.get('app-plus', {}).get('distribute', {}).get('icons', {}).get('android') or android.get('icons', {})
    if icons:
        hashes = {}
        for relative in icons.values():
            if not isinstance(relative, str) or not relative:
                continue
            icon = Path(relative)
            if not icon.is_absolute() or not icon.is_file():
                icon = Path(project) / relative.lstrip('/')
            if not icon.is_file():
                raise RuntimeError('缺少 Android 图标文件：' + relative + '；检查图标资源并执行 demo:prepare。')
            hashes[relative] = hashlib.sha256(icon.read_bytes()).hexdigest()
        source.update(icons=icons, iconFiles=hashes)
    return hashlib.sha256(json.dumps(source, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def require_current_base(apk, root=ROOT):
    expected = fingerprint(root)
    with zipfile.ZipFile(apk) as archive:
        stamps = {match.decode() for name in archive.namelist() if name.endswith('.dex')
                  for match in re.findall(rb'hfv1:[0-9a-f]{64}', archive.read(name))}
    if expected not in stamps:
        raise RuntimeError('原生代码与调试基座不匹配。执行 npm run android:base 重建；'
                           '手工制作基座前先执行 npm run android:prepare。页面同步不能更新原生代码。')
    return expected


def adb_path():
    roots = [os.environ.get('ANDROID_HOME'), os.environ.get('ANDROID_SDK_ROOT'),
             str(Path.home() / 'Library/Android/sdk'), str(Path.home() / 'Android/Sdk'),
             str(Path(os.environ.get('LOCALAPPDATA', '.')) / 'Android/Sdk')]
    for root in roots:
        for name in ['adb', 'adb.exe']:
            path = Path(root or '') / 'platform-tools' / name
            if root and path.is_file():
                return str(path)
    path = shutil.which('adb')
    if path:
        return path
    raise RuntimeError('未找到 ADB，请安装 Android SDK platform-tools 或设置 ANDROID_HOME。')


def devices(adb):
    result = []
    for line in run([adb, 'devices', '-l']).splitlines():
        parts = line.split()
        if len(parts) < 2 or parts[1] not in ('device', 'offline', 'unauthorized', 'recovery'):
            continue
        details = dict(p.split(':', 1) for p in parts[2:] if ':' in p)
        result.append({'serial': parts[0], 'state': parts[1], 'model': details.get('model', '').replace('_', ' ')})
    return result


def select_device(adb, serial=None):
    available = devices(adb)
    if serial:
        match = next((d for d in available if d['serial'] == serial), None)
        if not match:
            raise RuntimeError(f'设备 {serial} 未连接。执行 npm run android:devices 查看设备。')
        if match['state'] != 'device':
            raise RuntimeError(f'设备状态为 {match["state"]}；请重新连接并在手机上授权 USB 调试。')
        return match
    online = [d for d in available if d['state'] == 'device']
    if len(online) == 1:
        return online[0]
    if not online:
        raise RuntimeError('没有已授权的在线设备。执行 npm run android:devices 查看离线或待授权设备。')
    raise RuntimeError('有多台在线设备，请使用 --device 序列号明确选择；脚本不会自动切换手机。')


def broadcast(target, package, suffix, extras=None):
    command = target + ['shell', 'am', 'broadcast', '--receiver-foreground', '--include-stopped-packages', '-n', package + '/' + RECEIVER,
                        '-a', ACTION + suffix]
    for key, value in (extras or {}).items():
        command += ['--es', key, value]
    output = run(command, timeout=30)
    line = next((line for line in output.splitlines() if 'Broadcast completed:' in line and 'data=' in line), '')
    raw = line.partition('data=')[2].strip()
    if raw.startswith('"') and raw.endswith('"'):
        raw = raw[1:-1]
    try:
        response = json.loads(raw)
    except (ValueError, TypeError):
        raise RuntimeError('调试接收器未响应。请保持示例在手机前台，并确认已安装当前自定义基座。') from None
    if response.get('protocol') != 1:
        raise RuntimeError('调试协议版本不匹配，请重建基座。')
    code = response.get('code')
    if code != 'OK':
        hints = {'NOT_DEBUGGABLE': '当前安装的是正式包，请安装自定义调试基座。',
                 'BUSY': '人脸操作正在进行，请先返回示例页面再同步。',
                 'SYNC_FAILED': '资源校验或替换失败，原页面已保留。'}
        raise RuntimeError(f'{code}: {hints.get(code, "请重建基座并重试。")}' +
                           (f' 阶段：{response["phase"]}' if response.get('phase') else ''))
    return response


def resource_zip(directory):
    directory = Path(directory).resolve()
    output = io.BytesIO()
    total = 0
    count = 0
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(directory.rglob('*')):
            if path.is_symlink():
                raise RuntimeError('导出资源含符号链接，请重新导出普通文件。')
            if not path.is_file():
                continue
            count += 1
            if count > 512:
                raise RuntimeError('调试资源超过 512 个文件，请使用 HBuilderX 常规运行。')
            total += path.stat().st_size
            if total > MAX_BYTES:
                raise RuntimeError('调试资源超过 32 MB，请使用 HBuilderX 常规运行。')
            archive.write(path, path.relative_to(directory).as_posix())
    data = output.getvalue()
    if len(data) > MAX_BYTES:
        raise RuntimeError('压缩包超过 32 MB，请使用 HBuilderX 常规运行。')
    return data


def sync_resources(target, package, appid, directory, expected):
    info = broadcast(target, package, 'INFO')
    if info.get('fingerprint') != expected:
        raise RuntimeError('手机中基座的源码指纹不同，请重新安装本机已校验的基座。')
    request = uuid.uuid4().hex
    relative = f'files/helloface-debug/{request}.zip'
    data = resource_zip(directory)
    sha = hashlib.sha256(data).hexdigest()
    run(target + ['shell', 'run-as', package, 'mkdir', '-p', 'files/helloface-debug'])
    try:
        # tee opens the private file under the app UID; shell never touches external app directories.
        result = subprocess.run(target + ['shell', '-T', 'run-as', package, 'tee', relative], input=data,
                                stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=30)
        if result.returncode:
            raise RuntimeError('无法写入调试包私有目录，请确认安装的是可调试基座。')
        response = broadcast(target, package, 'SYNC', {'appid': appid, 'request': request, 'sha256': sha})
        if response.get('request') != request or response.get('sha256') != sha or response.get('fingerprint') != expected:
            raise RuntimeError('资源同步回执不匹配，停止启动。')
        return response
    finally:
        run(target + ['shell', 'run-as', package, 'rm', '-f', relative])


def log_snapshot(target, package):
    pid = app_pids(target, package)
    if not pid:
        raise RuntimeError('应用未运行，请先执行 npm run android:run。')
    # Filtering is also performed on the host for Android 6 logcat compatibility.
    output = run(target + ['logcat', '-d', '-v', 'threadtime', 'HelloFaceVerify:I', 'AndroidRuntime:E', '*:S'])
    lines = []
    for line in output.splitlines():
        match = re.match(r'\S+\s+\S+\s+(\d+)\s+\d+\s+[VDIWEF]\s+', line)
        if match and match[1] in pid:
            lines.append(re.sub(r'HF1:[A-Za-z0-9_-]+', '[redacted feature]', line))
    return '\n'.join(lines)


def app_pids(target, package):
    result = subprocess.run(target + ['shell', 'pidof', package], capture_output=True, text=True, timeout=10)
    if result.returncode == 0:
        return [value for value in result.stdout.split() if value.isdigit()]
    # Older vendor Android 6 images may not ship pidof.
    rows = run(target + ['shell', 'ps']).splitlines()
    if not rows or 'PID' not in rows[0].split():
        return []
    index = rows[0].split().index('PID')
    return [parts[index] for line in rows[1:] if (parts := line.split()) and
            len(parts) > index and parts[-1] == package and parts[index].isdigit()]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'devices', 'logs'])
    parser.add_argument('--project', type=Path, default=ROOT)
    parser.add_argument('--device')
    parser.add_argument('--follow', action='store_true', help='Follow current app processes until Ctrl+C')
    parser.add_argument('--duration', type=float, default=0, help='Optional follow duration in seconds')
    args = parser.parse_args()
    if args.action == 'prepare':
        print('已生成原生源码指纹：' + prepare())
        print('现在可以制作自定义调试基座；仅修改 Vue 页面无需重建。')
        return
    adb = adb_path()
    if args.action == 'devices':
        for device in devices(adb):
            print(f'{device["serial"]}  {device["state"]}  {device["model"]}')
        return
    manifest = json.loads((args.project.resolve() / 'manifest.json').read_text())
    android = manifest.get('app-plus', {}).get('distribute', {}).get('android') or manifest.get('app-android', {}).get('distribute', {})
    package = android.get('packagename', '')
    if not re.fullmatch(r'[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+', package, re.ASCII):
        raise RuntimeError('manifest.json 中的 Android 包名无效。')
    device = select_device(adb, args.device)
    target = [adb, '-s', device['serial']]
    if not args.follow:
        print(log_snapshot(target, package) or '当前进程尚无插件操作日志。')
        return
    started = time.monotonic()
    if args.duration < 0:
        raise RuntimeError('日志跟踪时长不能为负数。')
    print(f'跟踪 {package} 当前进程日志；Ctrl+C 结束。', flush=True)
    seen = set()
    waiting = False
    while not args.duration or time.monotonic() - started < args.duration:
        try:
            lines = log_snapshot(target, package).splitlines()
            for line in lines:
                if line not in seen:
                    print(line, flush=True)
            seen = (seen | set(lines)) if len(seen) < 2000 else set(lines)
            waiting = False
        except RuntimeError:
            if not waiting:
                print('等待该 App 启动；重启后自动继续跟踪。', flush=True)
            waiting = True
        time.sleep(1)


if __name__ == '__main__':
    try:
        main()
    except KeyboardInterrupt:
        raise SystemExit(0)
    except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired, zipfile.BadZipFile) as error:
        raise SystemExit('Android 调试失败：' + str(error))
