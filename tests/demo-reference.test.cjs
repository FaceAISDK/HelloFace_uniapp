const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { createHash } = require('node:crypto')

test('demo image, Base64 and SDK-extracted external feature refer to one 200x200 fixture', () => {
  const root = path.resolve(__dirname, '..')
  const png = fs.readFileSync(path.join(root, 'static/demo-face.png'))
  const reference = JSON.parse(fs.readFileSync(path.join(root, 'demo/face-reference.json')))
  const source = fs.readFileSync(path.join(root, 'demo/face-reference.uts'), 'utf8')
  assert.equal(source, fs.readFileSync(path.join(root, 'demo/face-reference.js'), 'utf8'))
  const constants = Object.fromEntries(Array.from(source.matchAll(/export const (\w+) = ("[^"\n]*")/g), m => [m[1], JSON.parse(m[2])]))
  assert.equal(png.readUInt32BE(16), 200)
  assert.equal(png.readUInt32BE(20), 200)
  assert.equal(createHash('sha256').update(png).digest('hex'), reference.imageSha256)
  assert.deepEqual(Buffer.from(constants.demoImageBase64, 'base64'), png)
  assert.equal(constants.demoFeature, reference.feature)
  assert.match(reference.feature, /^HF1:[A-Za-z0-9_-]{600}$/)
  assert.equal(constants.demoFeatureSpaceID, 'jdx-feature-v1')
  assert.equal(reference.sdkVersion, '0.8.8')
  assert.equal(reference.sdkVersion, JSON.parse(fs.readFileSync(path.join(root, 'sdk-artifacts.json'))).version)
})
